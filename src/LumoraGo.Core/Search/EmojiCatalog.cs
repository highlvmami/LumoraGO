    /// <summary>Adında veya anahtar kelimelerinde geçenler; adı arananla başlayanlar önde.</summary>
    public static IReadOnlyList<EmojiEntry> Search(string text, int max)
    {
        var folded = FuzzyMatcher.Fold(text.Trim());
        if (folded.Length == 0)
        {
            return All.Take(max).ToList();
        }

        return All
            .Select(e => (Entry: e, Name: FuzzyMatcher.Fold(e.Name), Words: FuzzyMatcher.Fold(e.Keywords)))
            .Select(x => (x.Entry, Score: x.Name.StartsWith(folded, StringComparison.Ordinal) ? 3
                : x.Words.Split(' ').Any(w => w.StartsWith(folded, StringComparison.Ordinal)) ? 2
                : x.Name.Contains(folded, StringComparison.Ordinal) || x.Words.Contains(folded, StringComparison.Ordinal) ? 1 : 0))
            .Where(x => x.Score > 0)
            .OrderByDescending(x => x.Score)
            .Take(max)
            .Select(x => x.Entry)
            .ToList();
    }
